// Builds the release ZIP (architecture §20.2): copies only what the extension needs, refuses to
// ship anything key-shaped, checks the versions agree, and writes a reproducible ZIP.
//
//   node scripts/package.mjs                    dist/pagewise-v<version>/ and dist/pagewise-v<version>.zip
//   node scripts/package.mjs --check            every check, nothing written (CI)
//   node scripts/package.mjs --tag v1.0.0       also check the tag (the release workflow passes it)
//   node scripts/package.mjs --notes v1.0.0     print that version's CHANGELOG.md section (release notes)
//
// No dependencies: the ZIP is written with node:zlib, entries sorted and timestamped at a fixed
// date, so the same sources always give the same bytes.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { deflateRawSync, inflateRawSync } from 'node:zlib';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The only things that ship. Tests, practice, docs, node_modules and .git never do (EC-REL-04). */
export const INCLUDE = ['manifest.json', 'src', 'vendor', 'assets'];
/** Never shipped, even inside an included folder. */
const JUNK_RE = /(^|\/)(\.DS_Store|Thumbs\.db|\.gitkeep|desktop\.ini)$|\.map$|(^|\/)\./;
/** Shapes of Gemini, Groq and Claude keys (§20.2, EC-SET-13). */
export const KEY_PATTERNS = [
  /AIza[0-9A-Za-z_-]{35}/, /AQ\.[A-Za-z0-9._~+/=-]{30,}/, /gsk_[A-Za-z0-9]{20,}/, /sk-ant-[A-Za-z0-9_-]{20,}/
];
/** Generated by `npm run sync`: a ZIP without them can't protect fields on the page (EC-REL-05). */
const GENERATED = ['src/content/generated/field-rules.classic.js', 'src/content/generated/action-rules.classic.js'];
const TEXT_RE = /\.(js|mjs|json|html|css|md|txt|svg)$|LICENSE[^/]*$/;
/** 1 Jan 2020, 00:00 local DOS time: every entry gets it, so builds are reproducible. */
const DOS_DATE = ((2020 - 1980) << 9) | (1 << 5) | 1;

/**
 * @typedef {{ name: string, data: Buffer }} Entry name: forward-slash path inside the package
 */

export class PackageError extends Error {}

// ---- Collecting ----

/**
 * Every file under the included paths, sorted, junk left out.
 * @param {string} root
 * @returns {Entry[]}
 */
export function collectFiles(root = ROOT) {
  /** @type {Entry[]} */
  const out = [];
  /** @param {string} abs */
  const walk = (abs) => {
    const name = relative(root, abs).split(sep).join('/');
    if (JUNK_RE.test(name)) return;
    if (statSync(abs).isDirectory()) {
      for (const child of readdirSync(abs)) walk(join(abs, child));
    } else {
      out.push({ name, data: readFileSync(abs) });
    }
  };
  for (const item of INCLUDE) walk(join(root, item));
  return out.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

// ---- Checks ----

/**
 * The manifest, package.json and the tag must name the same version (EC-REL-03). A tag may add a
 * pre-release suffix: v0.9.0-rc1 ships manifest version 0.9.0 (Chrome versions are numbers only).
 * @param {{ manifest: string, pkg: string, tag?: string|null }} v
 */
export function checkVersions({ manifest, pkg, tag }) {
  const problems = [];
  if (!/^\d+(\.\d+){0,3}$/.test(manifest)) problems.push(`manifest.json version "${manifest}" isn't a Chrome version (1 to 4 numbers).`);
  if (manifest !== pkg) problems.push(`manifest.json says ${manifest} but package.json says ${pkg}.`);
  if (tag) {
    const m = /^v(\d+(?:\.\d+){0,3})(-[0-9A-Za-z.-]+)?$/.exec(tag);
    if (!m) problems.push(`Tag "${tag}" isn't of the form v1.2.3 or v1.2.3-rc1.`);
    else if (m[1] !== manifest) problems.push(`Tag ${tag} is for version ${m[1]}, but manifest.json says ${manifest}.`);
  }
  if (problems.length) throw new PackageError(`Versions don't match:\n  ${problems.join('\n  ')}`);
}

/**
 * Anything shaped like an API key, with where it is (§20.2).
 * @param {Entry[]} entries
 * @returns {string[]} "path:line" for each hit
 */
export function findSecrets(entries) {
  const hits = [];
  for (const { name, data } of entries) {
    const text = data.toString('latin1'); // binary files too: a key in a PNG's metadata still counts
    if (!KEY_PATTERNS.some((re) => re.test(text))) continue;
    text.split('\n').forEach((line, i) => {
      if (KEY_PATTERNS.some((re) => re.test(line))) hits.push(`${name}:${i + 1}`);
    });
  }
  return hits;
}

/**
 * Package paths that shouldn't be there (EC-REL-04).
 * @param {string[]} names
 */
export function unexpectedPaths(names) {
  return names.filter((n) => {
    const top = n.split('/')[0];
    return !INCLUDE.includes(n) && !INCLUDE.includes(top) ||
      JUNK_RE.test(n) || /(^|\/)(node_modules|tests?|practice|docs|\.git)(\/|$)/.test(n) || n.includes('..');
  });
}

/**
 * Files the extension loads, each of which must be in the package: the manifest's pages, worker and
 * icons, the content scripts it injects, the HTML pages' scripts and styles, and every relative
 * ES-module import. A missing one would only show up as a broken install.
 * @param {Entry[]} entries
 * @returns {string[]} "<missing> (needed by <who>)"
 */
export function missingFiles(entries) {
  const have = new Set(entries.map((e) => e.name));
  /** @type {Array<[string, string]>} [path, needed by] */
  const needs = [];
  const text = (/** @type {string} */ n) => entries.find((e) => e.name === n)?.data.toString('utf8') ?? '';

  const manifest = JSON.parse(text('manifest.json') || '{}');
  for (const p of [
    manifest.background?.service_worker, manifest.side_panel?.default_path, manifest.options_page,
    ...Object.values(manifest.icons ?? {}), ...Object.values(manifest.action?.default_icon ?? {})
  ]) if (p) needs.push([String(p), 'manifest.json']);

  for (const n of GENERATED) needs.push([n, 'npm run sync']);

  // Content scripts are injected by path (src/background/tab-context.js → CONTENT_FILES).
  const contentList = /const CONTENT_FILES = \[([\s\S]*?)\];/.exec(text('src/background/tab-context.js'))?.[1] ?? '';
  for (const m of contentList.matchAll(/'([^']+)'/g)) needs.push([m[1], 'tab-context.js CONTENT_FILES']);

  for (const { name } of entries) {
    if (name.endsWith('.html')) {
      for (const m of text(name).matchAll(/<(?:script|link)\b[^>]*?\b(?:src|href)="([^"#?:]+)"/g)) {
        needs.push([posix.normalize(posix.join(posix.dirname(name), m[1])), name]);
      }
    } else if (name.endsWith('.js')) {
      for (const m of text(name).matchAll(/(?:\bfrom\s*|\bimport\s*\(\s*|^\s*import\s+)['"](\.{1,2}\/[^'"]+)['"]/gm)) {
        needs.push([posix.normalize(posix.join(posix.dirname(name), m[1])), name]);
      }
    }
  }
  return [...new Set(needs.filter(([p]) => !have.has(p)).map(([p, who]) => `${p} (needed by ${who})`))];
}

// ---- ZIP ----

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
/** @param {Buffer} buf */
export function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/**
 * A ZIP of these entries, in this order, every one deflated and stamped with the same date.
 * @param {Entry[]} entries
 * @returns {Buffer}
 */
export function createZip(entries) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const nameBuf = Buffer.from(name, 'utf8');
    const packed = deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed: 2.0 (deflate)
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(8, 8); // deflate
    local.writeUInt16LE(0, 10); // time 00:00
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(packed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBuf, packed);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE((3 << 8) | 20, 4); // made by: Unix, 2.0
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(0, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(packed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt32LE(((0o100644 << 16) >>> 0), 38); // -rw-r--r--
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += 30 + nameBuf.length + packed.length;
  }
  const dir = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(dir.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, dir, end]);
}

/**
 * Read a ZIP back (for the self-check, and tests): every entry's name and contents, CRC-checked.
 * @param {Buffer} zip
 * @returns {Entry[]}
 */
export function readZip(zip) {
  const endAt = zip.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (endAt < 0) throw new PackageError('Not a ZIP: no end of central directory.');
  const count = zip.readUInt16LE(endAt + 10);
  let at = zip.readUInt32LE(endAt + 16);
  /** @type {Entry[]} */
  const out = [];
  for (let i = 0; i < count; i++) {
    if (zip.readUInt32LE(at) !== 0x02014b50) throw new PackageError('Broken central directory.');
    const method = zip.readUInt16LE(at + 10);
    const crc = zip.readUInt32LE(at + 16);
    const size = zip.readUInt32LE(at + 20);
    const nameLen = zip.readUInt16LE(at + 28);
    const extraLen = zip.readUInt16LE(at + 30);
    const commentLen = zip.readUInt16LE(at + 32);
    const localAt = zip.readUInt32LE(at + 42);
    const name = zip.toString('utf8', at + 46, at + 46 + nameLen);
    const dataAt = localAt + 30 + zip.readUInt16LE(localAt + 26) + zip.readUInt16LE(localAt + 28);
    const raw = zip.subarray(dataAt, dataAt + size);
    const data = method === 8 ? inflateRawSync(raw) : Buffer.from(raw);
    if (crc32(data) !== crc) throw new PackageError(`CRC mismatch in ${name}.`);
    out.push({ name, data });
    at += 46 + nameLen + extraLen + commentLen;
  }
  return out;
}

// ---- Release notes ----

/**
 * One version's section of CHANGELOG.md ("## [1.0.0] - 2026-11-28" up to the next "## ").
 * A pre-release tag falls back to its base version, then to "Unreleased".
 * @param {string} changelog
 * @param {string} tag e.g. v1.0.0 or v0.9.0-rc1
 * @returns {string}
 */
export function changelogSection(changelog, tag) {
  const version = tag.replace(/^v/, '');
  const base = version.replace(/-.*$/, '');
  const sections = changelog.split(/^(?=## )/m);
  for (const wanted of [version, base, 'Unreleased']) {
    const found = sections.find((s) => new RegExp(`^## \\[?${wanted.replace(/[.]/g, '\\.')}\\]?(\\s|$)`).test(s));
    if (found) return found.replace(/^## [^\n]*\n/, '').trim();
  }
  throw new PackageError(`CHANGELOG.md has no section for ${version}, ${base} or Unreleased.`);
}

// ---- Build ----

/**
 * Run every check and build the ZIP in memory.
 * @param {{ root?: string, tag?: string|null }} [opts]
 * @returns {{ version: string, label: string, entries: Entry[], zip: Buffer }}
 */
export function buildPackage({ root = ROOT, tag = null } = {}) {
  const manifest = JSON.parse(readFileSync(join(root, 'manifest.json'), 'utf8'));
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  checkVersions({ manifest: manifest.version, pkg: pkg.version, tag });

  // The classic copies of the safety rules must match their sources (EC-REL-05).
  try {
    execFileSync(process.execPath, [join(root, 'scripts', 'sync-classic.mjs'), '--check'], { cwd: root, stdio: 'pipe' });
  } catch (err) {
    const detail = /** @type {any} */ (err).stderr?.toString().trim();
    throw new PackageError(`The generated safety rules are out of date. Run npm run sync and commit.\n  ${detail ?? ''}`);
  }

  const entries = collectFiles(root);
  const secrets = findSecrets(entries);
  if (secrets.length) throw new PackageError(`Something shaped like an API key would ship. Remove it:\n  ${secrets.join('\n  ')}`);
  const missing = missingFiles(entries);
  if (missing.length) throw new PackageError(`Files the extension loads are missing:\n  ${missing.join('\n  ')}`);

  const zip = createZip(entries);
  // Read it back: what's inside is exactly what we meant to ship (EC-REL-04).
  const inside = readZip(zip);
  const bad = unexpectedPaths(inside.map((e) => e.name));
  if (bad.length) throw new PackageError(`Unexpected files in the ZIP:\n  ${bad.join('\n  ')}`);
  if (inside.length !== entries.length) throw new PackageError('The ZIP lost files on the way.');

  const label = tag ?? `v${manifest.version}`;
  return { version: manifest.version, label, entries, zip };
}

/** @param {string[]} argv */
function main(argv) {
  const value = (/** @type {string} */ flag) => {
    const i = argv.indexOf(flag);
    return i >= 0 ? argv[i + 1] ?? null : null;
  };
  const notesFor = value('--notes');
  if (notesFor) {
    process.stdout.write(`${changelogSection(readFileSync(join(ROOT, 'CHANGELOG.md'), 'utf8'), notesFor)}\n`);
    return;
  }

  const check = argv.includes('--check');
  const { label, entries, zip } = buildPackage({ tag: value('--tag') });
  const kb = (zip.length / 1024).toFixed(0);
  if (check) {
    console.log(`ok: ${entries.length} files would ship as pagewise-${label}.zip (${kb} KB). Nothing written (--check).`);
    return;
  }
  const dist = join(ROOT, 'dist');
  const folder = join(dist, `pagewise-${label}`);
  rmSync(folder, { recursive: true, force: true });
  for (const { name, data } of entries) {
    mkdirSync(dirname(join(folder, name)), { recursive: true });
    writeFileSync(join(folder, name), data);
  }
  writeFileSync(join(dist, `pagewise-${label}.zip`), zip);
  console.log(`wrote dist/pagewise-${label}/ and dist/pagewise-${label}.zip: ${entries.length} files, ${kb} KB`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) { // real paths: see sync-classic.mjs
  try {
    main(process.argv.slice(2));
  } catch (err) {
    console.error(err instanceof PackageError ? `package: ${err.message}` : err);
    process.exit(1);
  }
}
