// Generates classic-script copies of the shared safety rules for content scripts (architecture §14.6).
// Content scripts can't `import`, so each canonical ES module in src/shared/safety/ (import-free,
// ending in one `export { … };` line) is copied with that line swapped for a namespace assignment:
//   (globalThis.__sahayakShared ??= {}).fieldRules = { classifyField, … };
// The copy is wrapped in an IIFE so injecting it into the same page twice doesn't redeclare its
// constants. tests/safety/sync.test.js fails if a committed copy is out of date.
//
//   npm run sync            write the copies
//   npm run sync -- --check exit 1 if any copy is out of date (CI)

import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const SOURCES = [
  { from: 'src/shared/safety/field-rules.js', to: 'src/content/generated/field-rules.classic.js', ns: 'fieldRules' },
  { from: 'src/shared/safety/action-rules.js', to: 'src/content/generated/action-rules.classic.js', ns: 'actionRules' }
];

/**
 * @param {string} source canonical module text
 * @param {string} ns property on globalThis.__sahayakShared
 * @param {string} from path, for messages
 * @returns {string} classic script text
 */
export function toClassic(source, ns, from) {
  const lines = source.replace(/\s+$/, '').split('\n');
  const last = lines.pop() ?? '';
  const match = /^export \{ ([\w$, ]+) \};$/.exec(last);
  if (!match) throw new Error(`${from} must end with a single "export { … };" line`);
  if (/^\s*(import|export)\b/m.test(lines.join('\n'))) throw new Error(`${from} must have no other import or export`);
  return [
    `// GENERATED by scripts/sync-classic.mjs from ${from}. Do not edit: change the source and run \`npm run sync\`.`,
    '(() => {',
    ...lines,
    `(globalThis.__sahayakShared ??= {}).${ns} = { ${match[1]} };`,
    '})();',
    ''
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const { from, to, ns } of SOURCES) {
    const expected = toClassic(readFileSync(join(ROOT, from), 'utf8'), ns, from);
    let current = null;
    try {
      current = readFileSync(join(ROOT, to), 'utf8');
    } catch {
      /* not generated yet */
    }
    if (current === expected) continue;
    if (check) {
      console.error(`out of date: ${to} (run npm run sync)`);
      stale++;
    } else {
      mkdirSync(dirname(join(ROOT, to)), { recursive: true });
      writeFileSync(join(ROOT, to), expected);
      console.log(`wrote ${to}`);
    }
  }
  if (stale) process.exit(1);
}

// Compare real paths: run through a symlink (macOS /var → /private/var), a plain comparison would
// skip main() and `--check` would pass without checking anything.
if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) main();
